#!/usr/bin/env node

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import {
  APERTURE_X,
  APERTURE_Y,
  GENERIC_APERTURE_GEOMETRY,
  apertureEnergyNormalization,
  apertureKernelIntegral,
  apertureUniformSample,
  averageUniformAperture,
  relativeBacklightGain,
} from "../models/nintendo-ags-101/reference/panel-optics.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const modelDir = path.join(root, "models", "nintendo-ags-101");
const sourcePath = path.join(modelDir, "data", "ws6-panel-optics-v1.json");
const colorPath = path.join(modelDir, "generated", "hcs-e688fc5-color.json");
const basePresetPath = path.join(modelDir, "presets", "period-reconstruction-v1.slangp");
const shaderPath = path.join(modelDir, "shaders", "ags101-display-v1.slang");
const presetDir = path.join(modelDir, "generated", "ws6-presets-v1");
const manifestPath = path.join(presetDir, "manifest.json");
const reportPath = path.join(modelDir, "generated", "ws6-validation-v1.json");
const checkOnly = process.argv.includes("--check");

const sha256 = (data) => crypto.createHash("sha256").update(data).digest("hex");
const jsonBuffer = (value) => Buffer.from(`${JSON.stringify(value, null, 2)}\n`);
const clean = (value) => typeof value === "number"
  ? Number(value.toPrecision(12))
  : (Array.isArray(value)
    ? value.map(clean)
    : (value && typeof value === "object"
      ? Object.fromEntries(Object.entries(value).map(([key, item]) => [key, clean(item)]))
      : value));

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function writeOrCheck(file, buffer) {
  const relative = path.relative(root, file);
  if (checkOnly) {
    assert(fs.existsSync(file), `${relative} is missing`);
    assert(fs.readFileSync(file).equals(buffer), `${relative} is stale`);
    return;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (!fs.existsSync(file) || !fs.readFileSync(file).equals(buffer)) {
    fs.writeFileSync(file, buffer);
    process.stdout.write(`Wrote ${relative}.\n`);
  }
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function overrideParameters(source, overrides) {
  let result = source;
  for (const [name, value] of Object.entries(overrides)) {
    const pattern = new RegExp(`^(${escapeRegExp(name)}\\s*=\\s*)"[^"]*"$`, "m");
    assert(pattern.test(result), `base AGS preset has no ${name} parameter`);
    result = result.replace(pattern, `$1"${value}"`);
  }
  return result;
}

function generatedPreset(base, spec) {
  const body = overrideParameters(base, spec.overrides)
    .replaceAll("## Provenance: ../REFERENCES.md", "## Provenance: ../../REFERENCES.md")
    .replace(/^(shader\d+\s*=\s*)"\.\.\/shaders\//gm, '$1"../../shaders/')
    .replace(/^(GtgRateLut\s*=\s*)"\.\.\/generated\//gm, '$1"../');
  return Buffer.from([
    "## Generated by tools/build-ags101-ws6.mjs; do not edit by hand.",
    "## Provenance: ../../REFERENCES.md",
    "## Evidence: [AGS-COLOR-01] [AGS-BACKLIGHT-01] [AGS-APERTURE-01]",
    `## ${spec.description}`,
    "",
    body.trimEnd(),
    "",
  ].join("\n"));
}

const sourceBuffer = fs.readFileSync(sourcePath);
const source = JSON.parse(sourceBuffer);
const colorBuffer = fs.readFileSync(colorPath);
const color = JSON.parse(colorBuffer);
const basePreset = fs.readFileSync(basePresetPath, "utf8");
assert(source.schemaVersion === 1, "invalid WS6 source schema");
assert(color.outputPolicies?.hcsBlackSubtracted?.id === "hcs-black-subtracted",
  "HCS generated profile has no named black-subtracted policy");
assert(color.outputPolicies?.hcsPhysicalBlack?.id === "hcs-physical-black",
  "HCS generated profile has no named physical-black policy");
assert(color.coverage?.notMeasuredOrNotRecorded?.brightnessMode === true,
  "HCS generated profile lost brightness-mode coverage limit");

const specs = [
  {
    id: "hcs-black-subtracted",
    description: "Named HCS output: measured static color with the HCS black-subtracted rendering policy.",
    overrides: { HcsMeasuredColor: "1.0", HcsImproveContrast: "1.0", BacklightScaleEnabled: "0.0" },
  },
  {
    id: "hcs-physical-black",
    description: "Named HCS output: restore the measured black XYZ of the pinned unit/protocol state.",
    overrides: { HcsMeasuredColor: "1.0", HcsImproveContrast: "0.0", BacklightScaleEnabled: "0.0" },
  },
  ...source.aperture.sensitivityVariants.map((variant) => ({
    id: `aperture-${variant.id}`,
    description: `Generic-prior aperture sensitivity ${variant.id}; this is not an AGS-specific optical measurement.`,
    overrides: {
      ApertureEnabled: "1.0",
      ApertureHorizontalRadius: variant.horizontalRadiusSubpixels.toFixed(2),
      ApertureVerticalRadius: variant.verticalRadiusPixels.toFixed(2),
      ApertureGain: "1.0",
    },
  })),
  {
    id: "aperture-rgb-order-control",
    description: "Generic-prior RGB order control; BGR remains the normal uncalibrated candidate.",
    overrides: { ApertureEnabled: "1.0", BGR: "0.0" },
  },
  {
    id: "backlight-relative-low-sensitivity",
    description: "Project sensitivity only: static relative gain 0.75; not a measured AGS-101 low/high ratio.",
    overrides: { BacklightScaleEnabled: "1.0", BacklightRelativeGain: "0.75" },
  },
];

const presetEntries = [];
for (const spec of specs) {
  const file = path.join(presetDir, `${spec.id}-v1.slangp`);
  const buffer = generatedPreset(basePreset, spec);
  writeOrCheck(file, buffer);
  presetEntries.push({
    id: spec.id,
    path: path.relative(modelDir, file),
    sha256: sha256(buffer),
    overrides: spec.overrides,
  });
}

const manifest = {
  schemaVersion: 1,
  manifestId: "nintendo-ags-101-ws6-presets-v1",
  generatedBy: "tools/build-ags101-ws6.mjs",
  sourceSha256: sha256(sourceBuffer),
  basePresetSha256: sha256(Buffer.from(basePreset)),
  presets: presetEntries,
};
const manifestBuffer = jsonBuffer(manifest);
writeOrCheck(manifestPath, manifestBuffer);

const fixtureScales = [4, 5, 6, 3.5, 3.75, 4.25];
const geometryResults = [];
let maximumMeanError = 0;
let maximumNeutralityError = 0;
for (const variant of source.aperture.sensitivityVariants) {
  const geometry = {
    horizontalRadiusSubpixels: variant.horizontalRadiusSubpixels,
    verticalRadiusPixels: variant.verticalRadiusPixels,
  };
  for (const scale of fixtureScales) {
    const mean = averageUniformAperture(12, 8, scale, scale, geometry);
    const meanError = Math.max(...mean.map((value) => Math.abs(value - 1)));
    const neutralityError = Math.max(...mean) - Math.min(...mean);
    maximumMeanError = Math.max(maximumMeanError, meanError);
    maximumNeutralityError = Math.max(maximumNeutralityError, neutralityError);
    geometryResults.push({ variant: variant.id, scale, meanRgbLinear: mean, meanError, neutralityError });
  }
}

const nominal = GENERIC_APERTURE_GEOMETRY;
const phaseSamples = [
  { id: "first-third", x: 1 / 6 },
  { id: "middle-third", x: 1 / 2 },
  { id: "last-third", x: 5 / 6 },
].map(({ id, x }) => ({
  id,
  bgr: apertureUniformSample(x, 0.5, 12, 4, { ...nominal, order: "bgr" }),
  rgb: apertureUniformSample(x, 0.5, 12, 4, { ...nominal, order: "rgb" }),
}));
const orderReverses = phaseSamples.every((sample) => (
  Math.abs(sample.bgr[0] - sample.rgb[2]) < 1e-12
  && Math.abs(sample.bgr[1] - sample.rgb[1]) < 1e-12
  && Math.abs(sample.bgr[2] - sample.rgb[0]) < 1e-12
));

// The 0.4999 Shader phase bias makes finite-grid means differ from one by a
// small deterministic amount at some fractional scales.  The bound is on the
// implemented sampling equation, not on a visual screenshot.
assert(maximumMeanError < 2e-3, `aperture mean-energy error ${maximumMeanError}`);
assert(maximumNeutralityError < 2e-3, `aperture neutrality error ${maximumNeutralityError}`);
assert(orderReverses, "RGB/BGR order control does not reverse channels exactly");
assert(relativeBacklightGain({ enabled: false, ratio: 0.5 }) === 1,
  "disabled backlight sensitivity changed static color");
assert(relativeBacklightGain({ enabled: true, ratio: 0.75 }) === 0.75,
  "enabled backlight sensitivity did not apply its explicit ratio");

const report = clean({
  schemaVersion: 1,
  reportId: "nintendo-ags-101-ws6-validation-v1",
  classification: "repository-cpu-equation-and-coverage-receipt-not-panel-measurement",
  generatedBy: "tools/build-ags101-ws6.mjs",
  sources: {
    panelOptics: path.relative(root, sourcePath),
    panelOpticsSha256: sha256(sourceBuffer),
    generatedColor: path.relative(root, colorPath),
    generatedColorSha256: sha256(colorBuffer),
    displayShader: path.relative(root, shaderPath),
    displayShaderSha256: sha256(fs.readFileSync(shaderPath)),
    presetManifest: path.relative(root, manifestPath),
    presetManifestSha256: sha256(manifestBuffer),
  },
  color: {
    measuredCoverage: source.staticColor.measurementCoverage,
    namedPolicies: source.staticColor.outputPolicies.map((policy) => policy.id),
    physicalBlackEncodedSrgb: color.goldenVectors.policies["hcs-physical-black"].grayscaleRgb555[0].outputRgb,
    blackSubtractedEncodedSrgb: color.goldenVectors.policies["hcs-black-subtracted"].grayscaleRgb555[0].outputRgb,
  },
  backlight: {
    establishedModes: source.backlight.established.userBrightnessModes,
    unknown: source.backlight.unknown,
    modulationSelected: false,
    pwmFrequencySelected: false,
    bypassGain: relativeBacklightGain({ enabled: false, ratio: 0.5 }),
    sensitivityGain: relativeBacklightGain({ enabled: true, ratio: 0.75 }),
  },
  aperture: {
    selectedClass: source.aperture.selected.claimClass,
    agsSpecificKernelGenerated: false,
    polynomialIntegrals: {
      horizontal: apertureKernelIntegral(APERTURE_X),
      vertical: apertureKernelIntegral(APERTURE_Y),
    },
    nominalNormalization: apertureEnergyNormalization(
      nominal.horizontalRadiusSubpixels, nominal.verticalRadiusPixels,
    ),
    fixtures: geometryResults,
    phaseSamples,
    maximumMeanError,
    maximumNeutralityError,
    orderReverses,
  },
  acceptance: {
    hcsCoverageSeparated: true,
    blackPoliciesNamedSeparately: true,
    backlightUnknownsExplicit: true,
    brightnessSensitivityIndependentBypass: true,
    genericAperturePriorExplicit: true,
    integerAndFractionalCpuEnergy: "pass",
    channelOrderAndNeutrality: "pass",
    shaderCompileAndSpirvValidation: "covered-by-current-ws3-receipt",
    gpuNumericApertureReadback: "deferred-to-ws8",
  },
});
writeOrCheck(reportPath, jsonBuffer(report));

process.stdout.write(checkOnly
  ? "AGS-101 WS6 generated artifacts are current.\n"
  : "Generated AGS-101 WS6 color/backlight/aperture artifacts.\n");
