const colorBuffer = fs.readFileSync(colorPath);
const color = JSON.parse(colorBuffer);
const gtgBuffer = fs.readFileSync(gtgPath);
const gtg = JSON.parse(gtgBuffer);
const stimulusBuffer = fs.readFileSync(stimulusPath);
const stimulus = JSON.parse(stimulusBuffer);
const parityScene = stimulus.scenes.find((scene) => scene.sceneId === "parity-toggle");
assert(parityScene?.type === "window-toggle"
  && parityScene.page0DwellFrames === 1 && parityScene.page1DwellFrames === 1,
"WS8 exposure reference requires the bounded one-frame parity-toggle window");
assert(parityScene.window?.x <= 120 && parityScene.window.x + parityScene.window.width > 120
  && parityScene.window.y <= 80 && parityScene.window.y + parityScene.window.height > 80,
"WS8 probe must remain inside the bounded parity-toggle window");
assert(parityScene.maxPageFlips <= 600 && parityScene.maximumDynamicSeconds <= 10.1
  && parityScene.terminalPage === 0,
"WS8 parity-toggle scene exceeds its live-stimulus safety boundary");
const alternatingCodes = [parityScene.page0WindowCode, parityScene.page1WindowCode];

const cells = new Map(gtg.cells.map((cell) => [cell.id, cell]));
const channels = ["r", "g", "b"];
function packedRate(fromCode, toCode, channel) {
  const from = Math.max(0, Math.min(31, fromCode));
  const to = Math.max(0, Math.min(31, toCode));
  const from0 = Math.floor(from);
  const from1 = Math.min(from0 + 1, 31);
  const to0 = Math.floor(to);
  const to1 = Math.min(to0 + 1, 31);
  const fromFraction = from - from0;
  const toFraction = to - to0;
  const rate = (fromIndex, toIndex) => {
    const cell = cells.get(`${channels[channel]}:${fromIndex}>${toIndex}`);
    assert(cell, `missing packed GtG cell ${channels[channel]}:${fromIndex}>${toIndex}`);
    return decodeRate16(encodeRate16(cell.ratePerSecond));
  };
  const low = rate(from0, to0) * (1 - toFraction) + rate(from0, to1) * toFraction;
  const high = rate(from1, to0) * (1 - toFraction) + rate(from1, to1) * toFraction;
  return low * (1 - fromFraction) + high * fromFraction;
}

const frameSeconds = 1_232 * 228 / 16_777_216;
const event = scanEvent({ row: 80, latchOffsetLines: 0, opticalDelaySeconds: 0 });
let panel = [...color.eotfRgb555Runtime[alternatingCodes[0]]];
let previous = [alternatingCodes[0], alternatingCodes[0], alternatingCodes[0]];
const lastByTarget = {};
let maximumCycleDrift = 0;
for (let frame = 0; frame < 2_048; frame += 1) {
  const code = alternatingCodes[frame % 2];
  const current = [code, code, code];
  const result = integrateScannedExposure({
    initialPanel: panel,
    oldTargetRgb555: previous,
    newTargetRgb555: current,
    opticalOnsetSeconds: event.opticalTimeInFrame,
    frameSeconds,
    eotfByCode: color.eotfRgb555Runtime,
    rateProvider: packedRate,
  });
  const key = current.join(",");
  if (lastByTarget[key] && frame >= 2_000) {
    maximumCycleDrift = Math.max(
      maximumCycleDrift,
      ...result.average.map((value, channel) => Math.abs(value - lastByTarget[key].average[channel])),
    );
  }
  lastByTarget[key] = {
    targetRgb555: current,
    average: result.average.map(stableReceiptNumber),
    endpoint: result.endpoint.map(stableReceiptNumber),
    frameParity: frame & 1,
  };
  panel = result.endpoint;
  previous = current;
}
assert(maximumCycleDrift < 1e-12, `alternating exposure cycle did not converge: ${maximumCycleDrift}`);

