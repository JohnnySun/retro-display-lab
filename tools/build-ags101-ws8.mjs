const colorPath = path.join(modelDir, "generated", "hcs-e688fc5-color.json");
const gtgPath = path.join(modelDir, "generated", "ws4-gtg-nominal-v1.json");
const stimulusPath = path.join(modelDir, "generated", "ws2-stimulus-v1", "manifest.json");
const responseShaderPath = path.join(modelDir, "shaders", "ags101-response-v1.slang");
const exposureShaderPath = path.join(modelDir, "shaders", "ags101-exposure-v1.slang");
const displayShaderPath = path.join(modelDir, "shaders", "ags101-display-v1.slang");
const outputDir = path.join(modelDir, "generated", "ws8-presets-v1");
const presetPath = path.join(outputDir, "exposure-numeric-v1.slangp");
const aperturePresetPath = path.join(outputDir, "aperture-energy-v1.slangp");
