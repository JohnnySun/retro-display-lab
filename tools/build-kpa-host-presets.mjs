import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const presetDir = path.join(root, "targets/konkr-gt78-vn/960x640-srgb-neutral/presets");
const checkOnly = process.argv.includes("--check");

const profiles = [
  {
    source: "ags101-period-reconstruction-v1.slangp",
    output: "ags101-period-reconstruction-kpa-local-v1.slangp",
  },
  {
    source: "dmg01-reference-v1.slangp",
    output: "dmg01-reference-kpa-local-v1.slangp",
  },
  {
    source: "dmg01-one-year-used-v1.slangp",
    output: "dmg01-one-year-used-kpa-local-v1.slangp",
  },
];

function build(profile) {
  let text = fs.readFileSync(path.join(presetDir, profile.source), "utf8").trimEnd();
  const countMatch = text.match(/^shaders = "(\d+)"$/m);
  if (!countMatch) throw new Error(`${profile.source}: missing shader count`);
  const pass = Number(countMatch[1]);
  text = text.replace(countMatch[0], `shaders = "${pass + 1}"`);

  const textureLine = text.match(/^textures = "([^"]+)"$/m);
  if (textureLine) {
    const names = textureLine[1].split(";");
    if (!names.includes("KpaHostLut")) names.push("KpaHostLut");
    text = text.replace(textureLine[0], `textures = "${names.join(";")}"`);
  } else {
    text = text.replace(
      /^shaders = "\d+"$/m,
      (line) => `${line}\n\ntextures = "KpaHostLut"`,
    );
  }

  return [
    "## Generated by tools/build-kpa-host-presets.mjs; do not edit by hand.",
    "## KPA RetroArch-local route: Android brightness 57, Gamma 7, neutral PQ, identity SurfaceFlinger.",
    "## Never combine with the Android-system KPA correction matrix.",
    text,
    "",
    `shader${pass} = "../host-correction/kpa-reference-b57-g7-v1/kpa-host-correction-v1.slang"`,
    `filter_linear${pass} = "false"`,
    `scale_type${pass} = "source"`,
    `scale${pass} = "1.0"`,
    "",
    "KpaHostLut = \"../host-correction/kpa-reference-b57-g7-v1/kpa-reference-b57-g7-v1-lut65.png\"",
    "KpaHostLut_linear = \"false\"",
    "KpaHostLut_wrap_mode = \"clamp_to_edge\"",
    "KpaHostLut_mipmap = \"false\"",
    "KpaHostCorrection = \"1.0\"",
    "",
  ].join("\n");
}

for (const profile of profiles) {
  const output = path.join(presetDir, profile.output);
  const expected = build(profile);
  if (checkOnly) {
    if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== expected) {
      throw new Error(`${profile.output} is stale; run tools/build-kpa-host-presets.mjs`);
    }
  } else {
    fs.writeFileSync(output, expected);
  }
}

console.log(`KPA complete local presets are ${checkOnly ? "current" : "generated"}.`);
