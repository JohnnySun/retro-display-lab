const sha256 = (data) => crypto.createHash("sha256").update(data).digest("hex");
const jsonBuffer = (value) => Buffer.from(`${JSON.stringify(value, null, 2)}\n`);

function clean(value) {
  if (typeof value === "number") {
    if (Math.abs(value) < 1e-15) return 0;
    return Number(value.toPrecision(12));
  }
  if (Array.isArray(value)) return value.map(clean);
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, clean(item)]));
  }
  return value;
}

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function writeOrCheck(file, buffer) {
  const relative = path.relative(root, file);
  if (checkOnly) {
    assert(fs.existsSync(file), `${relative} is missing`);
    assert(fs.readFileSync(file).equals(buffer), `${relative} is stale`);
    return;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (!fs.existsSync(file) || !fs.readFileSync(file).equals(buffer)) {
    fs.writeFileSync(file, buffer);
    process.stdout.write(`Wrote ${relative}.\n`);
  }
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function overrideParameters(source, overrides) {
  let result = source;
  for (const [name, value] of Object.entries(overrides)) {
    const pattern = new RegExp(`^(${escapeRegExp(name)}\\s*=\\s*)"[^"]*"$`, "m");
    assert(pattern.test(result), `base AGS preset has no ${name} parameter`);
    result = result.replace(pattern, `$1"${value}"`);
  }
  return result;
}

function generatedPreset(base, spec) {
  const body = overrideParameters(base, spec.overrides)
    .replaceAll("## Provenance: ../REFERENCES.md", "## Provenance: ../../REFERENCES.md")
    .replace(/^(shader\d+\s*=\s*)"\.\.\/shaders\//gm, '$1"../../shaders/')
    .replace(/^(GtgRateLut\s*=\s*)"\.\.\/generated\//gm, '$1"../');
  return Buffer.from([
    "## Generated by tools/build-ags101-ws7.mjs; do not edit by hand.",
    "## Provenance: ../../REFERENCES.md",
    "## Evidence: [AGS-GTGENSEMBLE-01] [AGS-TIMING-01] [AGS-BACKLIGHT-01] [AGS-EXPOSURE-01]",
    `## ${spec.description}`,
    "",
    body.trimEnd(),
    "",
  ].join("\n"));
}

function shaderFloatIntegral(start, target, rate, seconds) {
  const f = Math.fround;
  const k = Math.max(f(rate), f(1e-8));
  const dt = Math.max(f(seconds), 0);
  const decay = f(Math.exp(f(-f(k * dt))));
  return f(f(f(target) * dt)
    + f(f(f(start) - f(target)) * f(f(1) - decay) / k));
}

const definitionBuffer = fs.readFileSync(definitionPath);
const definition = JSON.parse(definitionBuffer);
const ensembleBuffer = fs.readFileSync(ensemblePath);
const ensemble = JSON.parse(ensembleBuffer);
const colorBuffer = fs.readFileSync(colorPath);
const color = JSON.parse(colorBuffer);
const ws6Buffer = fs.readFileSync(ws6Path);
const ws6 = JSON.parse(ws6Buffer);
const basePreset = fs.readFileSync(basePresetPath, "utf8");
const frameSeconds = definition.nativeClock.observationSeconds;
assert(definition.schemaVersion === 1, "invalid WS7 definition schema");
assert(Math.abs(frameSeconds - 1232 * 228 / 16777216) < 1e-18,
  "WS7 observation interval disagrees with exact WS3 clock");
assert(definition.backlightCandidates.excluded.some((item) => item.id === "pwm-dimming-unselected"),
  "WS7 definition silently selected PWM");

const profileById = Object.fromEntries(ensemble.members.map((member) => [member.id, member]));
const rateProvider = (member) => (fromCode, toCode) => {
  if (Math.abs(fromCode - toCode) < 1e-12) {
    const neighbor = toCode < 31 ? toCode + 1 : toCode - 1;
    return reconstructedTransition(member, toCode, neighbor).ratePerSecond;
  }
  return reconstructedTransition(member, fromCode, toCode).ratePerSecond;
};

function highResolutionAverageFromSegments(initialPanel, segments) {
  return initialPanel.map((initial, channel) => {
    let state = initial;
    let integral = 0;
    for (const segment of segments.filter((entry) => entry.channel === channel)) {
      const target = color.eotfRgb555Runtime[segment.toCode][channel];
      integral += compositeSimpsonFirstOrder(
        state, target, segment.rate, segment.seconds, 4096,
      );
      state = firstOrderState(state, target, segment.rate, segment.seconds);
    }
    return integral / frameSeconds;
  });
}

