function fail(message) {
  console.error(message);
  process.exit(1);
}

function sha256(buffer) {
  return crypto.createHash("sha256").update(buffer).digest("hex");
}

function jsonBuffer(value) {
  return Buffer.from(`${JSON.stringify(value, null, 2)}\n`);
}

function readJson(file) {
  if (!fs.existsSync(file)) fail(`${path.relative(root, file)} is missing`);
  const buffer = fs.readFileSync(file);
  return { buffer, value: JSON.parse(buffer) };
}

function assert(condition, message) {
  if (!condition) fail(message);
}

function close(actual, expected, label) {
  assert(Math.abs(actual - expected) <= Number.EPSILON * Math.max(1, Math.abs(expected)) * 8,
    `${label} does not reproduce from exact platform constants`);
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function overrideParameters(source, overrides) {
  let result = source;
  for (const [name, value] of Object.entries(overrides)) {
    const pattern = new RegExp(`^(${escapeRegExp(name)}\\s*=\\s*)"[^"]*"$`, "m");
    assert(pattern.test(result), `base AGS preset has no ${name} parameter`);
    result = result.replace(pattern, `$1"${value}"`);
  }
  return result;
}

function writeOrCheck(file, buffer) {
  const relative = path.relative(root, file);
  if (checkOnly) {
    assert(fs.existsSync(file), `${relative} is missing`);
    assert(fs.readFileSync(file).equals(buffer), `${relative} is stale`);
    return;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (!fs.existsSync(file) || !fs.readFileSync(file).equals(buffer)) {
    fs.writeFileSync(file, buffer);
    console.log(`Wrote ${relative}.`);
  }
}

function formatShaderFloat(value) {
  if (Number.isInteger(value)) return `${value}.0`;
  return Number(value).toPrecision(17).replace(/0+$/, "").replace(/\.$/, ".0");
}

function generatedTimingInclude(timing, constraintHash) {
  return Buffer.from(`// Generated by tools/build-ags101-ws3.mjs; do not edit by hand.\n// Provenance: ../REFERENCES.md\n// Evidence: [AGS-TIMING-01] [AGS-RECON-01]\n// Constraint SHA-256: ${constraintHash}\n\nconst float GBA_MASTER_CLOCK_HZ = ${formatShaderFloat(timing.masterClockHz)};\nconst float GBA_CYCLES_PER_LINE = ${formatShaderFloat(timing.cyclesPerLine)};\nconst float GBA_TOTAL_LINES = ${formatShaderFloat(timing.totalLinesPerFrame)};\nconst float LINE_SECONDS = GBA_CYCLES_PER_LINE / GBA_MASTER_CLOCK_HZ;\nconst float FRAME_SECONDS = LINE_SECONDS * GBA_TOTAL_LINES;\n\nstruct Ws3ScanEvent\n{\n   float rowStartSeconds;\n   float latchSeconds;\n   float opticalAbsoluteSeconds;\n   float opticalTimeInFrame;\n   uint sourceFrameOffset;\n};\n\nWs3ScanEvent ws3_scan_event(\n   int sourceRow,\n   float latchOffsetLines,\n   float opticalDelaySeconds)\n{\n   Ws3ScanEvent event;\n   event.rowStartSeconds = float(sourceRow) * LINE_SECONDS;\n   event.latchSeconds = event.rowStartSeconds\n      + clamp(latchOffsetLines, 0.0, 1.0) * LINE_SECONDS;\n   event.opticalAbsoluteSeconds = event.latchSeconds\n      + clamp(opticalDelaySeconds, 0.0, FRAME_SECONDS);\n   event.sourceFrameOffset = event.opticalAbsoluteSeconds >= FRAME_SECONDS\n      ? 1u\n      : 0u;\n   event.opticalTimeInFrame = event.opticalAbsoluteSeconds\n      - float(event.sourceFrameOffset) * FRAME_SECONDS;\n   return event;\n}\n\nfloat ws3_inversion_spatial_phase(ivec2 sourceCoord, float inversionTopology)\n{\n   int topology = int(floor(clamp(inversionTopology, 0.0, 3.0) + 0.5));\n   if (topology == 1)\n      return float(sourceCoord.y & 1);\n   if (topology == 2)\n      return float(sourceCoord.x & 1);\n   if (topology == 3)\n      return float((sourceCoord.x + sourceCoord.y) & 1);\n   return 0.0;\n}\n\nfloat ws3_drive_polarity(\n   uint frameCount,\n   ivec2 sourceCoord,\n   float parityPhase,\n   float inversionTopology)\n{\n   uint framePhase = frameCount\n      + uint(floor(clamp(parityPhase, 0.0, 1.0) + 0.5));\n   uint spatialPhase = uint(ws3_inversion_spatial_phase(\n      sourceCoord, inversionTopology\n   ));\n   return ((framePhase + spatialPhase) & 1u) == 0u ? 1.0 : -1.0;\n}\n`);
}

function candidatePreset(base, description, overrides) {
  const body = overrideParameters(base, overrides)
    .replaceAll("## Provenance: ../REFERENCES.md", "## Provenance: ../../REFERENCES.md")
    .replace(/^(shader\d+\s*=\s*)"\.\.\/shaders\//gm, '$1"../../shaders/')
    .replace(/^(GtgRateLut\s*=\s*)"\.\.\/generated\//gm, '$1"../');
  return Buffer.from([
    "## Generated by tools/build-ags101-ws3.mjs; do not edit by hand.",
    "## Provenance: ../../REFERENCES.md",
    "## Evidence: [AGS-TIMING-01] [AGS-RECON-01] [AGS-FRONTEND-01]",
    `## ${description}`,
    "## Sensitivity hypothesis only; no formal AGS-101 selection is made.",
    "",
    body.trimEnd(),
    "",
  ].join("\n"));
}

function expandIncludes(source, sourceDir, seen = new Set()) {
  return source.replace(/^\s*#include\s+"([^"]+)"\s*$/gm, (_match, relative) => {
    const includePath = path.resolve(sourceDir, relative);
    assert(!seen.has(includePath), `recursive Shader include: ${includePath}`);
    const nextSeen = new Set(seen).add(includePath);
    return expandIncludes(fs.readFileSync(includePath, "utf8"), path.dirname(includePath), nextSeen);
  });
}

function stageSource(shaderPath, stage) {
  const source = fs.readFileSync(shaderPath, "utf8");
  const vertexMarker = "#pragma stage vertex";
  const fragmentMarker = "#pragma stage fragment";
  const vertexIndex = source.indexOf(vertexMarker);
  const fragmentIndex = source.indexOf(fragmentMarker);
  assert(vertexIndex >= 0 && fragmentIndex > vertexIndex, `${path.basename(shaderPath)} has invalid stage markers`);
  const common = source.slice(0, vertexIndex);
  const stageBody = stage === "vert"
    ? source.slice(vertexIndex + vertexMarker.length, fragmentIndex)
    : source.slice(fragmentIndex + fragmentMarker.length);
  return expandIncludes(`${common}\n${stageBody}`, path.dirname(shaderPath))
    .replace(/^#pragma\s+(?:format|parameter).*$/gm, "");
}

function runShaderCompilation() {
  const compilerVersion = spawnSync("glslangValidator", ["--version"], { encoding: "utf8" });
  assert(compilerVersion.status === 0, "glslangValidator is required for --compile");
  const validatorVersion = spawnSync("spirv-val", ["--version"], { encoding: "utf8" });
  assert(validatorVersion.status === 0, "spirv-val is required for --compile");
  const scratch = fs.mkdtempSync(path.join(os.tmpdir(), "rdl-ags101-ws3-compile-"));
  const stages = [];
  try {
    for (const [shaderId, shaderPath] of [
      ["response", responseShaderPath],
      ["exposure", exposureShaderPath],
      ["display", displayShaderPath],
    ]) {
      for (const stage of ["vert", "frag"]) {
        const source = stageSource(shaderPath, stage);
        const sourcePath = path.join(scratch, `${shaderId}.${stage}`);
        const spirvPath = path.join(scratch, `${shaderId}.${stage}.spv`);
        fs.writeFileSync(sourcePath, source);
        const compile = spawnSync("glslangValidator", [
          "-V", "--target-env", "vulkan1.1", "-S", stage, "-o", spirvPath, sourcePath,
        ], { encoding: "utf8" });
        assert(compile.status === 0,
          `${shaderId} ${stage} compilation failed:\n${compile.stdout}\n${compile.stderr}`);
        const validate = spawnSync("spirv-val", ["--target-env", "vulkan1.1", spirvPath], {
          encoding: "utf8",
        });
        assert(validate.status === 0,
          `${shaderId} ${stage} SPIR-V validation failed:\n${validate.stdout}\n${validate.stderr}`);
        const spirv = fs.readFileSync(spirvPath);
        stages.push({
          shaderId,
          stage,
          expandedSourceSha256: sha256(Buffer.from(source)),
          spirvSha256: sha256(spirv),
          spirvBytes: spirv.length,
          pass: true,
        });
      }
    }
  } finally {
    fs.rmSync(scratch, { recursive: true, force: true });
  }
  return {
    schemaVersion: 1,
    receiptId: "nintendo-ags-101-ws3-shader-compile-v1",
    classification: "local-shader-compile-and-spirv-validation-receipt",
    capturedAt: new Date().toISOString(),
    tools: {
      glslangValidator: compilerVersion.stdout.trim().split("\n")[0],
      spirvVal: validatorVersion.stdout.trim().split("\n")[0],
      targetEnvironment: "vulkan1.1",
    },
    sources: {
      responseShaderSha256: sha256(fs.readFileSync(responseShaderPath)),
      exposureShaderSha256: sha256(fs.readFileSync(exposureShaderPath)),
      displayShaderSha256: sha256(fs.readFileSync(displayShaderPath)),
      sharedTimingIncludeSha256: sha256(fs.readFileSync(shaderIncludePath)),
    },
    stages,
    summary: { stages: stages.length, pass: stages.length === 6 && stages.every((entry) => entry.pass) },
    limits: "Compilation and SPIR-V validation prove Shader syntax/interface viability, not GPU numeric readback or AGS-101 hardware timing.",
  };
}

