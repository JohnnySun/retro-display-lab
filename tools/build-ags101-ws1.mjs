function fail(message) {
  console.error(message);
  process.exit(1);
}

function sha256(buffer) {
  return crypto.createHash("sha256").update(buffer).digest("hex");
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function overrideParameters(source, overrides) {
  let result = source;
  for (const [name, value] of Object.entries(overrides)) {
    const pattern = new RegExp(`^(${escapeRegExp(name)}\\s*=\\s*)"[^"]*"$`, "m");
    if (!pattern.test(result)) fail(`Base AGS preset has no ${name} parameter`);
    result = result.replace(pattern, `$1"${value}"`);
  }
  return result;
}

function targetPaths(source) {
  return source
    .replace(
      "## Provenance: ../REFERENCES.md",
      "## Model provenance: ../../../../models/nintendo-ags-101/REFERENCES.md",
    )
    .replace(
      /^(shader\d+\s*=\s*)"\.\.\/shaders\/([^"]+)"$/gm,
      '$1"../../../../models/nintendo-ags-101/shaders/$2"',
    )
    .replace(
      /^(GtgRateLut\s*=\s*)"\.\.\/generated\/([^"]+)"$/gm,
      '$1"../../../../models/nintendo-ags-101/generated/$2"',
    );
}

function generatedPreset(base, spec) {
  let body = overrideParameters(base, spec.overrides);
  if (spec.gtgRateLut) {
    body = body.replace(/^GtgRateLut\s*=\s*"[^"]*"$/m, `GtgRateLut = "${spec.gtgRateLut}"`);
  }
  if (spec.targetPaths) body = targetPaths(body);
  return [
    "## Generated by tools/build-ags101-ws1.mjs; do not edit by hand.",
    spec.description,
    "",
    body,
    "",
  ].join("\n");
}

function writeOrCheck(file, content) {
  const relative = path.relative(root, file);
  if (checkOnly) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content) {
      fail(`${relative} is missing or stale; run node tools/build-ags101-ws1.mjs`);
    }
    return false;
  }
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === content) return false;
  fs.writeFileSync(file, content);
  console.log(`Wrote ${relative}.`);
  return true;
}

