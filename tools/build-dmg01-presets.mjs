#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const modelPresetDir = path.join(root, "models", "nintendo-dmg-01", "presets");
const targetPresetDir = path.join(
  root,
  "targets",
  "konkr-gt78-vn",
  "960x640-srgb-neutral",
  "presets",
);
const basePath = path.join(modelPresetDir, "reference-v1.slangp");
const checkOnly = process.argv.includes("--check");

function fail(message) {
  console.error(message);
  process.exit(1);
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function overrideParameters(source, overrides) {
  let result = source;
  for (const [name, value] of Object.entries(overrides)) {
    const pattern = new RegExp(`^(${escapeRegExp(name)}\\s*=\\s*)"[^"]*"$`, "m");
    if (!pattern.test(result)) fail(`Base DMG preset has no ${name} parameter`);
    result = result.replace(pattern, `$1"${value}"`);
  }
  return result;
}

function targetShaderPaths(source) {
  return source
    .replace(
      "## Provenance: ../REFERENCES.md",
      "## Model provenance: ../../../../models/nintendo-dmg-01/REFERENCES.md",
    )
    .replace(
      /^(shader\d+\s*=\s*)"\.\.\/shaders\/([^"]+)"$/gm,
      '$1"../../../../models/nintendo-dmg-01/shaders/$2"',
    );
}

